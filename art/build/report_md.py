#!/usr/bin/env python3
"""Write ../COLLECTION_REPORT.md from build/report.json (run after build.py)."""
import json, os, collections

SP = os.path.dirname(os.path.abspath(__file__))
R = json.load(open(os.path.join(SP, 'report.json'), encoding='utf-8'))
OUT = os.path.join(os.path.dirname(SP), 'COLLECTION_REPORT.md')

BASE_FILES = ('works_painters.json', 'works_illus.json', 'enrich_painters.json', 'enrich_illus.json')
BASE_RAW = 725          # image-bearing records before this run (verified against the files 2026-09-30)
meta = R['artist_meta']
dbo = R.get('depth_by_origin', {})

before = {n: sum(v for o, v in d.items() if o in BASE_FILES) for n, d in dbo.items()}
after = {n: sum(d.values()) for n, d in dbo.items()}
new_works = sum(after.values()) - sum(before.values())
kind_works = collections.Counter()
for n, c in after.items():
    kind_works[meta[n]['kind']] += c
new_artists = [n for n, m in meta.items() if m.get('origin') == 'research-2026-09-30']
disc = collections.Counter(meta[n].get('disc') or '—' for n in new_artists)
excluded = len(R.get('excluded', []))
failed = len(R['failed'])
bfail = len(R.get('browser_failed', []))
dups = len(R['dup_url']) + len(R['dup_image'])

L = []
w = L.append
w('# Collection report\n')
w('Generated by `build/report_md.py` from `build/report.json` (build of %s). Counts come from the data '
  'that actually reached `explore.html`; nothing here is estimated.\n' % R['built'])
w('## Before → after\n')
w('| | before this run | now |')
w('|---|---:|---:|')
w('| Raw image records in the data files | %d | %d |' % (BASE_RAW, R['raw_records']))
w('| Verified unique works on the page | %d¹ | **%d** |' % (sum(before.values()), R['verified_unique_works']))
w('| Artists (all tabs, incl. study-only entries) | 197 | %d |' % R['artists'])
w('| Artists with at least one verified work | %d | %d |' % (sum(1 for v in before.values() if v), R['artists_with_works']))
w('| Largest single-artist collection | 8 (hard cap) | %d |' % max(after.values()))
w('')
w('¹ The earlier records re-checked today: of the 725 old records, %d passed the new fetch + in-browser checks '
  '(the old page also silently cut every artist to 8).\n' % sum(before.values()))
w('**New verified works added this run: %d.** New artists: %d (%s).\n' % (
    new_works, len(new_artists), ', '.join('%d %s' % (v, k) for k, v in disc.most_common())))
existing_gain = sum(after[n] - before.get(n, 0) for n in after if n not in new_artists)
new_gain = {k: sum(after.get(n, 0) for n in new_artists if (meta[n].get('disc') or '') == k) for k in ('close', 'adjacent', 'exploratory')}
tot = existing_gain + sum(new_gain.values())
w('Where the new works went (the brief suggested roughly 60 / 30 / 10): deeper collections of artists already in the '
  'data %d (%d%%) · new close or adjacent artists %d (%d%%) · exploratory artists %d (%d%%).\n' % (
      existing_gain, round(100 * existing_gain / tot), new_gain['close'] + new_gain['adjacent'],
      round(100 * (new_gain['close'] + new_gain['adjacent']) / tot), new_gain['exploratory'], round(100 * new_gain['exploratory'] / tot)))
w('### What did not make it\n')
w('| | count | where listed |')
w('|---|---:|---|')
w('| Duplicates collapsed (same URL at another size, or same picture by image hash) | %d | `report.json` → dup_url / dup_image |' % dups)
w('| Failed fetch verification (timeouts, too small, errors) | %d | `report.json` → failed |' % failed)
w('| Passed fetch but failed inside the browser | %d | `report.json` → browser_failed |' % bfail)
w('| Excluded after attribution check | %d | `build/data/exclusions.json` |' % excluded)
w('| Unverified (never fetched) | %d | `report.json` → unverified |' % len(R['unverified']))
w('')
w('## By tab and by kind\n')
w('| tab | artists | with works | works |')
w('|---|---:|---:|---:|')
for t, k in R['by_tab'].items():
    w('| %s | %d | %d | %d |' % ({'cont': 'Contemporary', 'illu': 'Illustrators', 'study': 'Study', 'past': 'Earlier'}.get(t, t), k['artists'], k['with_works'], k['works']))
w('')
w('Works by the artist\'s kind (medium is recorded separately per work where the source states it): ' +
  ', '.join('%s %d' % (k, v) for k, v in kind_works.most_common()) + '.\n')
w('## Verification coverage\n')
w('- Every work on the page has a fetch record (HTTP 200, `image/*`, decodes, short side ≥ 160 px) with '
  'pixel dimensions and a difference hash — %d / %d.' % (R['verified_unique_works'], R['verified_unique_works']))
w('- Every image was also loaded inside headless Chromium from a `file://` page with no referrer, as the real '
  'page does (`build/browser_probe.js`); failures are excluded at build time.')
w('- %d works have a lighter feed image (a size variant published by the same source, hash-matched to the full image).' % R['thumbnails'])
w('- %d works still use pixiv\'s `embed.pixiv.net` card image, which is a 1200×630 crop of the original — kept from '
  'the earlier data, flagged here; not used for new additions.' % R['pixiv_embed_crops'])
w('')
w('## Depth per artist\n')
w('Before = works from the four original data files that still verify; after = everything on the page now.\n')
w('| artist | kind | before | after |')
w('|---|---|---:|---:|')
for n, c in sorted(after.items(), key=lambda x: (-x[1], x[0])):
    w('| %s%s | %s | %d | %d |' % (n, (' ' + meta[n]['jp']) if meta[n].get('jp') else '', meta[n]['kind'], before.get(n, 0), c))
w('')
w('Artists with no verified images (reachable from the A–Z directory and search): %d.\n' % len(R['no_works']))
w('## Sources\n')
w('| source domain (work page) | works |')
w('|---|---:|')
for d, n in R['domains'][:40]:
    w('| %s | %d |' % (d, n))
w('')
open(OUT, 'w', encoding='utf-8').write('\n'.join(L))
print('written', OUT)
